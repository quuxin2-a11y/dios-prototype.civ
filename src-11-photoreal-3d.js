function t4OrbitStop() {
  if (T4.orb) {
    clearInterval(T4.orb);
    T4.orb = 0;
    try {
      T4.v.camera.lookAtTransform(window.Cesium.Matrix4.IDENTITY);
    } catch (e) {}
  }
}
function t4Orbit(lat, lon, gh, H) {
  var C = window.Cesium,
    v = T4.v;
  if (!v) return;
  t4OrbitStop();
  var ctr = C.Cartesian3.fromDegrees(lon, lat, gh || 0),
    r = Math.max(220, (H || 40) * 3.4),
    h0 = v.camera.heading,
    t0 = 0;
  try {
    v.camera.flyToBoundingSphere(new C.BoundingSphere(ctr, 1), {
      offset: new C.HeadingPitchRange(h0, -26 * D, r),
      duration: 1.8,
      complete: function () {
        t0 = Date.now();
        T4.orb = setInterval(function () {
          var a = (Date.now() - t0) / 1000;
          if (a > 40 || !T4.on) {
            t4OrbitStop();
            return;
          }
          try {
            v.camera.lookAt(ctr, new C.HeadingPitchRange(h0 + a * 0.2, -26 * D, r));
          } catch (e) {}
        }, 33);
      }
    });
  } catch (e) {}
}
