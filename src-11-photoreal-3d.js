  T4MT = now;
  var cg = v.camera.positionCartographic,
    clon = cg.longitude / D,
    clat = cg.latitude / D,
    seen = {};
  try {
    v.clock.shouldAnimate = true;
  } catch (x) {}
  var near = function (arr, max, deg) {
    var k = Math.cos(clat * D) || 1,
      o = [],
      i,
      a,
      dx,
      dy;
    for (i = 0; i < arr.length; i++) {
      a = arr[i];
      if (a.lat == null || a.lon == null) continue;
      dx = (((a.lon - clon + 540) % 360) - 180) * k;
      dy = a.lat - clat;
      if (Math.abs(dx) < deg && Math.abs(dy) < deg) o.push([dx * dx + dy * dy, a]);
    }
    o.sort(function (x, y) {
      return x[0] - y[0];
    });
    return o.slice(0, max).map(function (x) {
      return x[1];
    });
  };
