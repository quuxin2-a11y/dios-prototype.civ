    near(SATS, 50, 70).forEach(function (q) {
      put("t" + q.n, q, "sat", (q.alt || 400) * 1000, 90, q.iss ? 56 : 34, false, {
        trail: 40,
        step: 15000,
        tc: "#ffffff",
        tw: 1.5
      });
    });
