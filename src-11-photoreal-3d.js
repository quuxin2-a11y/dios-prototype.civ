// which model fits: aircraft by ADS-B emitter category (falling back to speed and height), ships by AIS ship type
function planeCls(p) {
  var c = p.cat || 0;
  if (c === 8) return "heli";
  if (c === 6 || c === 5) return "wide";
  if (c === 2 || c === 3) return "prop";
  if (c === 4) return "plane";
  return (p.v || 0) < 85 && (p.alt || 0) < 4500 ? "prop" : "plane";
}
function shipCls(q) {
  var t = q.st;
  if (t == null) return "ship";
  if (t >= 60 && t < 70) return "cruise";
  if (t >= 80 && t < 90) return "tanker";
  if ((t >= 30 && t < 38) || (t >= 50 && t < 60)) return "tug";
  return "ship";
}
